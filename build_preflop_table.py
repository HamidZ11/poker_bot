"""
Generates preflop_table.py: all 169 starting hands ranked by equity against
one random hand, measured with the engine's own evaluator.

    .venv/bin/python build_preflop_table.py > preflop_table.py

Takes a couple of minutes. Seeded per hand, so the output is repeatable. The
bot never imports this file, so it is not part of the submission.
"""

import multiprocessing
import random
import sys

from card_utils import RANKS, Card, evaluate, full_deck

TRIALS = 60_000  # per hand: a standard error of about 0.2%


def hand_classes() -> list[str]:
    """The 169 hands as "AA", "AKs", "AKo": high rank first."""
    high_first = RANKS[::-1]
    hands = []
    for i, high in enumerate(high_first):
        hands.append(high + high)
        for low in high_first[i + 1:]:
            hands += [high + low + "s", high + low + "o"]
    return hands


def combos(hand: str) -> int:
    """How many of the 1326 two-card hands this class holds."""
    return 6 if len(hand) == 2 else 4 if hand[2] == "s" else 12


def equity(hand: str) -> tuple[str, float]:
    """The hand's share of the pot against a random hand, ties split."""
    second_suit = "S" if hand.endswith("s") else "H"
    mine = [Card(hand[0], "S"), Card(hand[1], second_suit)]
    unseen = [card for card in full_deck() if card not in mine]
    rng = random.Random(hand)
    won = 0.0
    for _ in range(TRIALS):
        cards = rng.sample(unseen, 7)
        board = cards[:5]
        ours = evaluate(mine + board)
        theirs = evaluate(cards[5:] + board)
        won += 1.0 if ours > theirs else 0.5 if ours == theirs else 0.0
    return hand, won / TRIALS


def main():
    with multiprocessing.Pool() as pool:
        results = pool.map(equity, hand_classes(), chunksize=1)
    results.sort(key=lambda result: (-result[1], result[0]))
    total = sum(combos(hand) for hand, _ in results)
    print('"""')
    print("Generated by build_preflop_table.py: do not edit by hand.")
    print()
    print("EQUITY: each starting hand's share of the pot against one random")
    print("hand, strongest first. PERCENTILE: the share of all 1326 two-card")
    print("hands that are this strong or stronger, so a hand is in the \"top")
    print("30%\" when PERCENTILE[hand] <= 0.30.")
    print('"""')
    print()
    print("EQUITY = {")
    for hand, value in results:
        print(f'    "{hand}": {value:.4f},')
    print("}")
    print()
    print("PERCENTILE = {")
    seen = 0
    for hand, _ in results:
        seen += combos(hand)
        print(f'    "{hand}": {seen / total:.4f},')
    print("}")


if __name__ == "__main__":
    sys.exit(main())
