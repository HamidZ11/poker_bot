"""
Generates preflop_ranges.py: every starting hand's equity against ranges from
the top 5% of hands to all of them, in 5% steps. It saves simulating preflop
all-in decisions during play.

    .venv/bin/python build_range_table.py > preflop_ranges.tmp
    mv preflop_ranges.tmp preflop_ranges.py

Takes a few minutes. Seeded per hand, so the output is repeatable. The bot
never imports this file, so it is not part of the submission.
"""

import multiprocessing
import random
import sys

from build_preflop_table import hand_classes
from card_utils import Card, evaluate, full_deck
from preflop_table import PERCENTILE

TRIALS = 6_000  # per hand and range: a standard error of about 0.6%
STEPS = 20  # range widths: 1/STEPS, 2/STEPS, ... 1
OUTSIDE_RANGE = 0.02  # as in model.py: hands outside the range stay possible


def key(first: Card, second: Card) -> str:
    high, low = sorted((first, second), key=lambda c: c.value, reverse=True)
    if high.rank == low.rank:
        return high.rank + low.rank
    return high.rank + low.rank + ("s" if high.suit == low.suit else "o")


def row(hand: str) -> tuple[str, list[float]]:
    second_suit = "S" if hand.endswith("s") else "H"
    mine = [Card(hand[0], "S"), Card(hand[1], second_suit)]
    deck = [card for card in full_deck() if card not in mine]
    combos = [
        (first, second, PERCENTILE[key(first, second)])
        for i, first in enumerate(deck)
        for second in deck[i + 1:]
    ]
    rng = random.Random(hand)
    equities = []
    for step in range(1, STEPS + 1):
        limit = step / STEPS
        weights = [1.0 if c[2] <= limit else OUTSIDE_RANGE for c in combos]
        won = 0.0
        for first, second, _ in rng.choices(combos, weights, k=TRIALS):
            drawn = rng.sample(deck, 7)
            board = [c for c in drawn if c != first and c != second][:5]
            ours = evaluate(mine + board)
            theirs = evaluate([first, second] + board)
            won += 1.0 if ours > theirs else 0.5 if ours == theirs else 0.0
        equities.append(won / TRIALS)
    return hand, equities


def main():
    with multiprocessing.Pool() as pool:
        rows = pool.map(row, hand_classes(), chunksize=1)
    print('"""')
    print("Generated by build_range_table.py: do not edit by hand.")
    print()
    print("RANGE_EQUITY[hand][i]: the hand's share of the pot against the top")
    print(f"(i + 1) / {STEPS} of all hands, by preflop_table.PERCENTILE.")
    print('"""')
    print()
    print(f"RANGE_STEPS = {STEPS}")
    print()
    print("RANGE_EQUITY = {")
    for hand, equities in rows:
        values = ", ".join(f"{value:.3f}" for value in equities)
        print(f'    "{hand}": ({values}),')
    print("}")


if __name__ == "__main__":
    sys.exit(main())
